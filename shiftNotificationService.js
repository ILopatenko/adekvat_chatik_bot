const { pool } = require('./dbConnection');

function getUserName(user) {
   const name = [user.first_name, user.last_name].filter(Boolean).join(' ');

   if (user.username) {
      return `${name || `ID ${user.telegram_id}`} (@${user.username})`;
   }

   return name || `ID ${user.telegram_id}`;
}

function getActivityText(messages) {
   if (messages >= 1000) {
      return 'прямо кипел от общения';
   }

   if (messages >= 500) {
      return 'получился очень оживлённым';
   }

   if (messages >= 200) {
      return 'получился довольно активным';
   }

   if (messages >= 50) {
      return 'прошёл вполне бодренько';
   }

   if (messages >= 10) {
      return 'получился спокойным и уютным';
   }

   return 'прошёл тихонько и спокойно';
}

async function getShiftStatistics(shiftId) {
   const result = await pool.query(
      `
    SELECT
      COALESCE(SUM(messages), 0)::BIGINT AS messages,
      COALESCE(SUM(photos), 0)::BIGINT AS photos,
      COALESCE(SUM(videos), 0)::BIGINT AS videos,
      COALESCE(SUM(voice_messages), 0)::BIGINT AS voice_messages
    FROM shift_user_stats
    WHERE shift_id = $1
    `,
      [shiftId],
   );

   const topResult = await pool.query(
      `
    SELECT
      u.telegram_id,
      u.username,
      u.first_name,
      u.last_name,
      s.messages
    FROM shift_user_stats s
    JOIN users u
      ON u.id = s.user_id
    WHERE s.shift_id = $1
      AND s.messages > 0
    ORDER BY s.messages DESC
    LIMIT 3
    `,
      [shiftId],
   );

   return {
      messages: Number(result.rows[0].messages),
      photos: Number(result.rows[0].photos),
      videos: Number(result.rows[0].videos),
      voiceMessages: Number(result.rows[0].voice_messages),
      topUsers: topResult.rows.map(user => ({
         name: getUserName(user),
         messages: Number(user.messages),
      })),
   };
}

function formatTopUsers(topUsers) {
   const medals = ['🥇', '🥈', '🥉'];

   if (!topUsers.length) {
      return 'Сегодня у нас все были скромными и тихонькими! 🥰🐾';
   }

   return topUsers
      .map((user, index) => `${medals[index]} **${user.name}** — **${user.messages} сообщений**`)
      .join('\n');
}

function formatStatistics(statistics) {
   return [
      `💬 Сообщений — **${statistics.messages}**`,
      `📸 Фотографий — **${statistics.photos}**`,
      `🎬 Видео — **${statistics.videos}**`,
      `🎤 Голосовых сообщений — **${statistics.voiceMessages}**`,
   ].join('\n');
}

